// ── Render helpers ────────────────────────────────────────────

function TermList({ block }) {
  return (
    <div className="space-y-2">
      <p className="text-[11px] font-medium text-muted-foreground uppercase tracking-wider">{block.title}</p>
      <dl className="grid grid-cols-1 md:grid-cols-2 gap-2.5">
        {block.terms.map((item) => (
          <div key={item.term} className="rounded-lg border border-border p-3 bg-card">
            <dt className="text-xs font-semibold text-foreground">{item.term}</dt>
            <dd className="text-[11px] text-muted-foreground leading-relaxed mt-1">{item.def}</dd>
          </div>
        ))}
      </dl>
    </div>
  );
}

function DataTable({ block }) {
  return (
    <div className="space-y-2">
      <p className="text-[11px] font-medium text-muted-foreground uppercase tracking-wider">{block.title}</p>
      <div className="rounded-lg border border-border overflow-hidden">
        <table className="w-full text-left">
          <thead className="bg-muted/50">
            <tr>
              {block.head.map((h) => (
                <th key={h} className="px-3 py-2 text-[10px] font-medium text-muted-foreground uppercase tracking-wider whitespace-nowrap">{h}</th>
              ))}
            </tr>
          </thead>
          <tbody className="divide-y divide-border">
            {block.rows.map((row, i) => (
              <tr key={i}>
                {row.map((cell, j) => (
                  <td key={j} className={`px-3 py-2 align-top text-[11px] leading-relaxed ${j === 0 ? "font-medium text-foreground" : "text-muted-foreground"}`}>
                    {cell}
                  </td>
                ))}
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

function Callout({ block }) {
  return (
    <div className="rounded-lg border border-blue-200 dark:border-blue-500/20 bg-blue-50 dark:bg-blue-500/10 p-3.5 flex gap-3">
      <Info className="w-4 h-4 text-blue-500 shrink-0 mt-0.5" />
      <div>
        <p className="text-xs font-medium text-foreground">{block.title}</p>
        <p className="text-[11px] text-muted-foreground leading-relaxed mt-1">{block.text}</p>
      </div>
    </div>
  );
}

function SectionBlock({ block }) {
  switch (block.type) {
    case "terms": return <TermList block={block} />;
    case "table": return <DataTable block={block} />;
    case "callout": return <Callout block={block} />;
    default: return null;
  }
}

export default function GlossaryPage() {
  const [activeId, setActiveId] = useState(glossarySections[0].id);
  const [query, setQuery] = useState("");
  const sectionRefs = useRef({});

  useEffect(() => {
    const viewport = document.querySelector('[data-slot="scroll-area-viewport"]');
    if (!viewport) return;

    const updateActive = () => {
      let current = glossarySections[0].id;
      for (const section of glossarySections) {
        const el = sectionRefs.current[section.id];
        if (el && el.getBoundingClientRect().top <= 120) current = section.id;
      }
      setActiveId(current);
    };

    viewport.addEventListener("scroll", updateActive, { passive: true });
    return () => viewport.removeEventListener("scroll", updateActive);
  }, []);

  const scrollToSection = (id) => {
    sectionRefs.current[id]?.scrollIntoView({ behavior: "smooth", block: "start" });
    setActiveId(id);
  };

  // Search across every term in the glossary
  const q = query.trim().toLowerCase();
  const filteredSections = glossarySections
    .map((section) => {
      if (!q) return section;
      const blocks = section.blocks
        .map((block) => {
          if (block.type !== "terms") return block;
          const terms = block.terms.filter(
            (t) => t.term.toLowerCase().includes(q) || t.def.toLowerCase().includes(q)
          );
          return terms.length ? { ...block, terms } : null;
        })
        .filter(Boolean);
      const tableMatch = section.blocks.some(
        (b) => b.type === "table" && (b.title || "").toLowerCase().includes(q)
      );
      return blocks.length || tableMatch ? { ...section, blocks: blocks.length ? blocks : section.blocks } : null;
    })
    .filter(Boolean);
  const totalTerms = glossarySections.reduce(
    (sum, s) => sum + s.blocks.filter((b) => b.type === "terms").reduce((n, b) => n + b.terms.length, 0),
    0
  );

  return (
    <ProtectedRoute>
      <div className="min-h-full bg-background p-4 sm:p-6 space-y-4">
        {/* Header */}
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-border/50">
          <div>
            <div className="inline-flex items-center px-2.5 py-0.5 rounded-full bg-primary/10 text-primary text-[10px] font-medium uppercase tracking-widest mb-2">
              Documentation
            </div>
            <h1 className="text-base font-semibold tracking-tight text-foreground">Glossary</h1>
            <p className="text-xs text-muted-foreground mt-0.5">
              {totalTerms} terms — the language of the tender-to-cash system, defined in plain English
            </p>
          </div>
          <Link
            href="/help/docs"
            className="inline-flex items-center gap-1.5 h-8 px-3 rounded-md border border-border text-xs font-medium text-muted-foreground hover:text-foreground hover:bg-muted transition-colors shrink-0"
          >
            <ArrowLeft className="w-3.5 h-3.5" />
            All Documents
          </Link>
        </div>

        {/* Search */}
        <div className="relative max-w-md">
          <Search className="w-3.5 h-3.5 absolute left-2.5 top-1/2 -translate-y-1/2 text-muted-foreground" />
          <input
            type="text"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search terms, e.g. retention, tax invoice, award..."
            className="h-8 w-full text-xs pl-8 pr-3 rounded-md bg-card border border-border outline-none focus:ring-2 focus:ring-primary/20"
          />
        </div>

        {filteredSections.length === 0 && (
          <Card>
            <CardContent className="p-8 text-center">
              <BookMarked className="w-8 h-8 mx-auto mb-2 text-muted-foreground/50" />
              <p className="text-sm font-medium text-foreground">No terms match &ldquo;{query}&rdquo;</p>
              <p className="text-xs text-muted-foreground mt-1">Try a broader word, or clear the search</p>
            </CardContent>
          </Card>
        )}

        <div className="grid grid-cols-1 lg:grid-cols-[220px_1fr] gap-4">
          {/* Rail */}
          {filteredSections.length > 0 && (
            <aside className="hidden lg:block">
              <div className="sticky top-6">
                <p className="text-[10px] font-medium text-muted-foreground uppercase tracking-widest mb-2 px-2">
                  Categories
                </p>
                <nav className="space-y-0.5">
                  {filteredSections.map((section) => {
                    const Icon = section.icon;
                    const active = activeId === section.id;
                    return (
                      <button
                        key={section.id}
                        onClick={() => scrollToSection(section.id)}
                        className={`w-full flex items-center gap-2 px-2 py-1.5 rounded-md text-[11px] font-medium transition-colors text-left ${
                          active ? "bg-primary/10 text-primary" : "text-muted-foreground hover:text-foreground hover:bg-muted"
                        }`}
                      >
                        <Icon className="w-3.5 h-3.5 shrink-0" />
                        <span className="truncate">{section.label}</span>
                      </button>
                    );
                  })}
                </nav>
              </div>
            </aside>
          )}

          {/* Content */}
          <div className="space-y-4 min-w-0">
            {filteredSections.map((section) => {
              const Icon = section.icon;
              return (
                <section
                  key={section.id}
                  id={section.id}
                  ref={(el) => { sectionRefs.current[section.id] = el; }}
                  className="scroll-mt-20"
                >
                  <Card>
                    <CardContent className="p-4 sm:p-5 space-y-4">
                      <div className="flex items-start gap-3 pb-3 border-b border-border/50">
                        <div className="p-2 rounded-lg bg-primary/10 text-primary shrink-0">
                          <Icon className="w-4.5 h-4.5" />
                        </div>
                        <div>
                          <h2 className="text-sm font-semibold text-foreground">{section.title}</h2>
                          <p className="text-[11px] text-muted-foreground leading-relaxed mt-1">{section.summary}</p>
                        </div>
                      </div>
                      {section.blocks.map((block, i) => (
                        <SectionBlock key={i} block={block} />
                      ))}
                    </CardContent>
                  </Card>
                </section>
              );
            })}
          </div>
        </div>
      </div>
    </ProtectedRoute>
  );
}
